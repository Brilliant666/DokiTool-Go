function classTokens(value: unknown): string[] {
  if (typeof value === 'string') return value.split(/\s+/);
  if (Array.isArray(value)) return value.flatMap(classTokens);
  if (value && typeof value === 'object') return Object.keys(value).filter(key => Boolean((value as Record<string, unknown>)[key]));
  return [];
}

/** Accept the same string / array / conditional class forms as Vue. */
export function iconForClass(value: unknown): IconPath | undefined {
  for (const token of classTokens(value)) {
    const name = Object.prototype.hasOwnProperty.call(iconNames, token) ? iconNames[token] : undefined;
    if (name) return paths[name];
  }
  return undefined;
}
